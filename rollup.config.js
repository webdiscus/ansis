/**
 * Remove comments.
 *
 * @param {string} string
 * @return {*}
 */
function removeComments(string) {
  return string.replace(/\/\*[\s\S]*?\*\/|(?<=[^:])\/\/.*|^\/\/.*/g, '').trim();
}

function inject({ filter, code }) {
  return {
    name: 'inject',
    transform(source, id) {
      if (filter(id)) {
        return {
          code: `${code}\n${source}`,
          map: null,
        };
      }
      return null;
    },
  };
}

/**
 * Convert Rollup/Terser named export aliases into a compact object destructuring export.
 *
 * Terser keeps public export names stable by creating minified local aliases first:
 * {red:a,green:b}=x;export{a as red,b as green,x as default}
 *
 * The ESM package can export the properties directly from the default Ansis instance:
 * export default x;export const{red,green}=x;
 *
 * The plugin derives the export list from the generated chunk, verifies that each named export
 * points to the same local binding as the preceding destructuring assignment, and then rewrites
 * only the final export tail.
 *
 * @returns {import('rollup').Plugin}
 */
function compactEsmExports() {
  return {
    name: 'compact-export',
    renderChunk(code, chunk) {
      if (!chunk.isEntry) return null;
      if (/\b(?:require|import)\s*\(|\bmodule\.exports\b|\bimport\s/.test(code)) {
        this.error('Unexpected CJS or runtime import in ESM build output.');
      }

      const exportMatch = code.match(/;?export\{([^}]*)};?$/);
      if (!exportMatch) {
        this.error('Cannot find the final ESM export list.');
      }

      const exports = new Map();
      for (const item of exportMatch[1].split(',')) {
        const [local, exported = local] = item.split(/\s+as\s+/);
        exports.set(exported, local);
      }

      const defaultBinding = exports.get('default');
      if (!defaultBinding) {
        this.error('Cannot find the default export binding.');
      }

      const destructuringMatch = code.match(new RegExp(`\\{([^}]*)\\}=${defaultBinding};?export\\{`));
      if (!destructuringMatch) {
        this.error('Cannot find the ESM named export destructuring.');
      }

      const namedExports = [];
      for (const item of destructuringMatch[1].split(',')) {
        const [name, local = name] = item.split(':');
        if (!exports.has(name)) continue;
        if (exports.get(name) !== local) {
          this.error(`Cannot compact ESM export "${name}".`);
        }
        namedExports.push(name);
      }

      for (const name of exports.keys()) {
        if (name !== 'default' && !namedExports.includes(name)) {
          this.error(`Cannot find compact source for ESM export "${name}".`);
        }
      }

      const start = code[destructuringMatch.index - 1] === ',' ? destructuringMatch.index - 1 : destructuringMatch.index;
      return {
        code: code.slice(0, start) + `;export default ${defaultBinding};export const{${namedExports.join(',')}}=${defaultBinding};`,
        map: null,
      };
    },
  };
}

/**
 * Minify d.ts file content by removing comments, insignificant spaces, new lines and trailing commas.
 *
 * @param {string} content
 * @return {string}
 */
function minifyDts(content) {
  return removeComments(content)
  .replaceAll(/\n/g, '')
  .replaceAll(/\s{2,}/g, ' ')
  .replaceAll(': ', ':')
  .replaceAll(' | ', '|')
  .replaceAll(' & ', '&')
  .replaceAll(' = ', '=')
  .replaceAll(' =', '=')
  .replaceAll('=|', '=')
  .replaceAll('=> ', '=>')
  .replaceAll(', ', ',')
  .replaceAll('{ ', '{')
  .replaceAll(' {', '{')
  .replaceAll(' }', '}')
  .replaceAll('; ', ';')
  .replaceAll(' ;', ';')
  .replaceAll(',}', '}')
  .replaceAll(';}', '}');
}

function buildDualConfig({ output, ecma }) {
  return {
    input: 'src/index.js',
    output: {
      file: `dist/${output}/index.cjs`,
      format: 'cjs',
      exports: 'named',
      intro: '/* Auto generated by rollup.\nUse `npm run build` to create new version. */',
      strict: false,
      esModule: false,
    },
    plugins: [
      ...(ecma < 2020
        ? [
            inject({
              filter: (id) => path.resolve(id).endsWith('src/index.js'),
              code: `typeof globalThis === 'undefined' && (global.globalThis = global);`,
            }),
          ]
        : []),
      replace({
        // allow modifying exports
        preventAssignment: false,

        // define default export for tsc using default import, e.g. `import ansis from 'ansis'`
        'exports.Ansis = Ansis': 'module.exports = ansis.default = ansis',
        'exports.default = ansis': '',

        // required for Node.js 10
        //'/* @node10:polyfills */': "typeof globalThis === 'undefined' && (global.globalThis = global);"
        //'globalThis': "typeof globalThis === 'undefined' && (global.globalThis = global);"
        //'globalThis': "typeof globalThis === 'undefined' ? global : globalThis"
        //'globalThis': "'QWERTZ'"
        //...(ecma < 2020 ? {'globalThis': "typeof globalThis === 'undefined' ? global : globalThis"} : {})
      }),
      ...(ecma < 2020 ? [babel(babelOptions)] : []),
      terser(terserOptions(ecma)),
      copy({
        targets: [
          {
            src: 'src/index.mjs',
            dest: `dist/${output}/`,
            transform: async (contents) => (
              await minify(
                // transform the extension of the source ESM file to output .cjs (it will be compiled to CommonJS)
                contents.toString().replace('.js', '.cjs'),
                { ecma }
              )
            ).code,
          },
          {
            src: 'src/index.d.ts',
            dest: `dist/${output}/`,
            rename: 'index.d.ts',
            transform: (contents) => minifyDts(contents.toString()),
          },
          { src: `package/${output}/package.json`, dest: `dist/${output}/` },
          { src: `package/${output}/README.md`, dest: `dist/${output}/` },
          { src: 'LICENSE', dest: `dist/${output}/` },
        ],
      }),
    ],
  };
}

function buildEsmConfig({ output, ecma }) {
  return {
    input: 'src/index.mjs',
    output: {
      file: `dist/${output}/index.js`,
      format: 'esm',
      intro: '/* Auto generated by rollup.\nUse `npm run build` to create new version. */',
    },
    plugins: [
      terser(terserOptions(ecma)),
      compactEsmExports(),
      copy({
        targets: [
          {
            src: 'src/index.d.ts',
            dest: `dist/${output}/`,
            rename: 'index.d.ts',
            transform: (contents) => minifyDts(contents.toString()),
          },
          { src: `package/${output}/package.json`, dest: `dist/${output}/` },
          { src: `package/${output}/README.md`, dest: `dist/${output}/` },
          { src: 'LICENSE', dest: `dist/${output}/` },
        ],
      }),
    ],
  };
}

export default [
  buildDualConfig({ output: 'dual-node10', ecma: 2018 }), // ES9 (ES2018), Node.js 10+
  buildDualConfig({ output: 'dual-node14', ecma: 2020 }), // ES11 (ES2020), Node.js 14+
  buildEsmConfig({ output: 'esm', ecma: 2022 }), // ES13 (ES2022), Node.js 18+
];
